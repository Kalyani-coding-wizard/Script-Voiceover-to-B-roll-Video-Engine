"""Licence-safe title-card fallback metadata."""
from __future__ import annotations

import hashlib

from footage_providers.base import FootageClip


def make_title_card_clip(scene_text: str, query: str, reason: str) -> FootageClip:
    clip_id = f"title_card_{hashlib.sha256(scene_text.encode('utf-8')).hexdigest()[:12]}"
    return FootageClip(
        url=f"generated://title-card/{clip_id}",
        source="title_card",
        licence="Original FFmpeg motion graphic",
        licence_url="https://ffmpeg.org/legal.html",
        source_url="",
        author="IncuBrix renderer",
        retrieved_at=None,
        attribution="Original motion graphic generated by IncuBrix",
        is_ai_generated=False,
        relevance_score=0.7,
        reason=reason,
        clip_id=clip_id,
        duration_seconds=6.0,
        width=1920,
        height=1080,
        extra={"description": query, "title": scene_text},
    )
